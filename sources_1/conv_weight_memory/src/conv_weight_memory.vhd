LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

--! Weight memory of one convolution channel.
--!
--! During the initialisation phase of the Kernel-Sliders all G_INPUT_AMOUNT weights are
--! copied out of a single port BRAM into registers, from where the computation unit
--! reads them for every kernel window.
--!
--! G_DATA_FILE_PATH points at one of the files generated by data/generate_bram_data.py, which
--! already contains exactly the weights of this channel in the order they are addressed.

ENTITY conv_weight_memory IS
	GENERIC (
		G_BIT_WIDTH    : NATURAL := 8;
		G_INPUT_AMOUNT : NATURAL := 25;
		--! amount of entries this memory holds; G_INPUT_AMOUNT for a single channel or a
		--! multiple of it when the channel is used for several output channels in series
		G_DEPTH          : NATURAL := 25;
		G_DATA_FILE_PATH : STRING  := "../data/output/conv_1_weights_ch000.data"
	);
	PORT (
		clk         : IN STD_LOGIC;
		rst         : IN STD_LOGIC;
		i_base_addr : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_DEPTH)))) - 1 DOWNTO 0);
		o_mem_valid : OUT STD_LOGIC;
		--! G_INPUT_AMOUNT weights, element i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		o_weights : OUT STD_LOGIC_VECTOR(G_INPUT_AMOUNT * G_BIT_WIDTH - 1 DOWNTO 0)
	);
END ENTITY conv_weight_memory;

ARCHITECTURE rtl OF conv_weight_memory IS

	--! The registered weights are held as an array so that they can be written with a
	--! dynamic index; they are flattened onto the output port below.

	TYPE t_weight_array IS ARRAY(0 TO G_INPUT_AMOUNT - 1) OF STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);

	SIGNAL s_old_addr     : UNSIGNED(integer(ceil(log2(real(G_DEPTH)))) - 1 DOWNTO 0);
	SIGNAL s_addr         : UNSIGNED(integer(ceil(log2(real(G_DEPTH)))) - 1 DOWNTO 0);
	SIGNAL s_base_addr    : UNSIGNED(integer(ceil(log2(real(G_DEPTH)))) - 1 DOWNTO 0);
	SIGNAL s_actual_addr  : STD_LOGIC_VECTOR(integer(ceil(log2(real(G_DEPTH)))) - 1 DOWNTO 0);
	SIGNAL s_weight_array : t_weight_array;

	SIGNAL s_din       : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_dout      : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_mem_valid : STD_LOGIC;
	SIGNAL s_rd_en     : STD_LOGIC;

BEGIN

	RESET_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN
				s_base_addr    <= unsigned(i_base_addr);
				s_old_addr     <= (OTHERS => '0');
				s_addr         <= (OTHERS => '0');
				s_weight_array <= (OTHERS => (OTHERS => '0'));
				s_mem_valid    <= '0';
			ELSE
				s_old_addr <= s_addr;

				IF s_addr < G_INPUT_AMOUNT - 1 THEN
					s_addr <= s_addr + 1;
				END IF;

				s_weight_array(to_integer(s_old_addr)) <= s_dout;

				IF s_old_addr >= G_INPUT_AMOUNT - 1 THEN
					s_mem_valid <= '1';
				END IF;
			END IF;
		END IF;

	END PROCESS RESET_PROC;

	s_actual_addr <= std_logic_vector(s_base_addr + s_addr);
	o_mem_valid   <= s_mem_valid;

	s_rd_en <= not s_mem_valid;
	s_din   <= (OTHERS => '0');

	BRAM_ENT : ENTITY work.bram_single_port
		GENERIC MAP (
			G_BIT_WIDTH      => G_BIT_WIDTH,
			G_DEPTH          => G_DEPTH,
			G_DATA_FILE_PATH => G_DATA_FILE_PATH
		)
		PORT MAP (
			clk     => clk,
			i_rd_en => s_rd_en,
			i_wr_en => '0',
			i_addr  => s_actual_addr,
			i_din   => s_din,
			o_dout  => s_dout
		);

	-- Mapping of output values

	OUTPUT_GEN : FOR i IN 0 TO G_INPUT_AMOUNT - 1 GENERATE
		o_weights((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH) <= s_weight_array(i);
	END GENERATE OUTPUT_GEN;

END ARCHITECTURE rtl;
