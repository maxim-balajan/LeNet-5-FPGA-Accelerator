LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

-- This unit computes all output channels for a given input channel;
-- If you want to parallelize an entire convolution step you need to instantiate this unit #total_input_channel times

ENTITY conv_par IS
	GENERIC (
		--! general generics that are necessary
		G_BIT_WIDTH         : NATURAL              := 8;
		G_INPUT_WIDTH       : NATURAL              := 32;
		G_INPUT_HEIGHT      : NATURAL              := 32;
		G_KERNEL_SIZE       : NATURAL              := 5;
		G_POOLING_SIZE      : INTEGER RANGE 2 TO 2 := 2;
		G_ENABLE_CLIP_ADDER : INTEGER RANGE 0 TO 1 := 1;

		--! generics used for initializing BRAM Weight Memory
		G_TOTAL_INPUT_CHANNEL  : NATURAL := 1;
		G_TOTAL_OUTPUT_CHANNEL : NATURAL := 6;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING  := "../data/output/conv_1_weights_ch";
		G_SCALE_ID           : NATURAL := 1;
		G_SCALE_FILE_PATH    : STRING  := "../data/scale_values.data"
	);
	PORT (
		clk            : IN STD_LOGIC;
		rst            : IN STD_LOGIC;
		i_pixel_stream : IN STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		i_valid_pixel  : IN STD_LOGIC;
		--! one pixel per output channel, channel i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		o_pixels_stream  : OUT STD_LOGIC_VECTOR(G_TOTAL_OUTPUT_CHANNEL * G_BIT_WIDTH - 1 DOWNTO 0);
		o_valid_pixel    : OUT STD_LOGIC;
		o_pixel_complete : OUT STD_LOGIC
	);
END ENTITY conv_par;

ARCHITECTURE rtl OF conv_par IS

	--! Reduces a control line to a single bit, replaces the VHDL-2008 unary "or"

	FUNCTION f_or_reduce (
		vector : STD_LOGIC_VECTOR
	) RETURN STD_LOGIC IS

		VARIABLE v_result : STD_LOGIC := '0';

	BEGIN

		FOR i IN vector'RANGE LOOP

			v_result := v_result OR vector(i);

		END LOOP;

		RETURN v_result;

	END FUNCTION f_or_reduce;

	-- Output of the Convolution Slider
	SIGNAL s_kernel_en         : STD_LOGIC;
	SIGNAL s_kernel_complete   : STD_LOGIC;
	SIGNAL s_activation_matrix : STD_LOGIC_VECTOR(G_KERNEL_SIZE ** 2 * G_BIT_WIDTH - 1 DOWNTO 0);

	-- Output of the Pipelines
	SIGNAL s_new_valid_pixels    : STD_LOGIC_VECTOR(0 TO G_TOTAL_OUTPUT_CHANNEL - 1);
	SIGNAL s_new_pixels_complete : STD_LOGIC_VECTOR(0 TO G_TOTAL_OUTPUT_CHANNEL - 1);

BEGIN

	CONV_SLIDER : ENTITY work.convolution_slider
		GENERIC MAP (
			G_BIT_WIDTH    => G_BIT_WIDTH,
			G_INPUT_WIDTH  => G_INPUT_WIDTH,
			G_INPUT_HEIGHT => G_INPUT_HEIGHT,
			G_KERNEL_SIZE  => G_KERNEL_SIZE
		)
		PORT MAP (
			clk                  => clk,
			rst                  => rst,
			i_pixel_stream       => i_pixel_stream,
			i_valid_pixel        => i_valid_pixel,
			o_kernel_complete    => s_kernel_complete,
			o_kernel_en          => s_kernel_en,
			o_kernel_activations => s_activation_matrix
		);

	PIPELINE_GEN : FOR i IN 0 TO G_TOTAL_OUTPUT_CHANNEL - 1 GENERATE

		PIPELINE_INST : ENTITY work.conv_pool_pipeline
			GENERIC MAP (
				G_BIT_WIDTH            => G_BIT_WIDTH,
				G_INPUT_WIDTH          => G_INPUT_WIDTH,
				G_INPUT_HEIGHT         => G_INPUT_HEIGHT,
				G_INPUT_AMOUNT         => G_KERNEL_SIZE ** 2,
				G_KERNEL_SIZE          => G_KERNEL_SIZE,
				G_POOLING_SIZE         => G_POOLING_SIZE,
				G_ENABLE_WEIGHTS       => 1,
				G_TOTAL_INPUT_CHANNEL  => G_TOTAL_INPUT_CHANNEL,
				G_TOTAL_OUTPUT_CHANNEL => G_TOTAL_OUTPUT_CHANNEL,
				G_CURRENT_CHANNEL      => i + 1,
				G_INIT_TYPE            => 0,
				G_WEIGHT_PATH_PREFIX   => G_WEIGHT_PATH_PREFIX,
				G_SCALE_ID             => G_SCALE_ID,
				G_SCALE_FILE_PATH      => G_SCALE_FILE_PATH,
				G_ENABLE_CLIP_ADDER    => G_ENABLE_CLIP_ADDER,
				-- Maybe make the following three generics to generics of this unit?
				-- For now keep it as is
				G_ENABLE_MUL_LINE => 1,
				G_ENABLE_SHIFT    => 1,
				G_ENABLE_RELU     => 1,
				G_OUT_BIT_WIDTH   => G_BIT_WIDTH
			)
			PORT MAP (
				clk               => clk,
				rst               => rst,
				i_activations     => s_activation_matrix,
				i_kernel_en       => s_kernel_en,
				i_kernel_complete => s_kernel_complete,
				i_base_addr       => open,
				-- Weights valid is not necessary for this unit
				-- but could be useful in sequential comp.
				o_weights_valid => open,
				o_pixel         => o_pixels_stream((i + 1) * G_BIT_WIDTH - 1 DOWNTO i * G_BIT_WIDTH),
				o_valid_pixel   => s_new_valid_pixels(i),
				o_comp_complete => s_new_pixels_complete(i)
			);

	END GENERATE PIPELINE_GEN;

	-- All pipelines should hopefully be synchronous
	o_valid_pixel    <= f_or_reduce(s_new_valid_pixels);
	o_pixel_complete <= f_or_reduce(s_new_pixels_complete);

END ARCHITECTURE rtl;
