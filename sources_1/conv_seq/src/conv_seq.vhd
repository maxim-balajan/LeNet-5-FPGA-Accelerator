LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

-- This unit computes all output channels for a given input channel;
-- If you want to parallelize an entire convolution step you need to instantiate this unit #total_input_channel times

ENTITY conv_seq IS
	GENERIC (
		--! general generics that are necessary
		G_BIT_WIDTH             : NATURAL              := 8;
		G_ACCUMULATOR_BIT_WIDTH : NATURAL              := 24;
		G_INPUT_WIDTH           : NATURAL              := 14;
		G_INPUT_HEIGHT          : NATURAL              := 14;
		G_KERNEL_SIZE           : NATURAL              := 5;
		G_POOLING_SIZE          : INTEGER RANGE 2 TO 2 := 2;
		G_ENABLE_CLIP_ADDER     : INTEGER RANGE 0 TO 1 := 1;

		--! generics used for initializing BRAM Weight Memory
		G_TOTAL_INPUT_CHANNEL  : NATURAL := 6;
		G_TOTAL_OUTPUT_CHANNEL : NATURAL := 16;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING  := "../data/output/conv_2_weights_ch";
		G_SCALE_ID           : NATURAL := 1;
		G_SCALE_FILE_PATH    : STRING  := "../data/scale_values.data"
	);
	PORT (
		clk : IN STD_LOGIC;
		rst : IN STD_LOGIC;
		--! one pixel per input channel, channel i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		i_pixel_stream         : IN STD_LOGIC_VECTOR(G_TOTAL_INPUT_CHANNEL * G_BIT_WIDTH - 1 DOWNTO 0);
		i_valid_pixel          : IN STD_LOGIC;
		o_pixels_stream        : OUT STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		o_valid_pixel          : OUT STD_LOGIC;
		o_pixel_complete       : OUT STD_LOGIC;
		o_pixel_output_channel : OUT STD_LOGIC_VECTOR(integer(ceil(log2(real(G_TOTAL_OUTPUT_CHANNEL)))) - 1 DOWNTO 0)
	);
END ENTITY conv_seq;

ARCHITECTURE rtl OF conv_seq IS

	--! Reduces a control line to a single bit, replaces the VHDL-2008 unary "or"

	FUNCTION f_or_reduce (
		vector : STD_LOGIC_VECTOR
	) RETURN STD_LOGIC IS

		VARIABLE v_result : STD_LOGIC := '0';

	BEGIN

		FOR i IN vector'RANGE LOOP

			v_result := v_result OR vector(i);

		END LOOP;

		RETURN v_result;

	END FUNCTION f_or_reduce;

	-- control signals
	SIGNAL s_channel_comp_complete  : STD_LOGIC;
	SIGNAL s_new_pixel_complete     : STD_LOGIC;
	SIGNAL s_current_output_channel : UNSIGNED(integer(ceil(log2(real(G_TOTAL_OUTPUT_CHANNEL)))) - 1 DOWNTO 0);
	SIGNAL s_channel_reset          : STD_LOGIC;

	-- fifo control signals
	SIGNAL s_streaming_fifo_rd_en : STD_LOGIC;

	-- fifo -> conv slider
	SIGNAL s_fifo_conv_pixel_stream : STD_LOGIC_VECTOR(G_TOTAL_INPUT_CHANNEL * G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_fifo_conv_pixel_valid  : STD_LOGIC_VECTOR(0 TO G_TOTAL_INPUT_CHANNEL - 1);

	-- conv slider -> conv pipeline
	SIGNAL s_conv_slider_conv_pipeline_kernel_complete          : STD_LOGIC_VECTOR(0 TO G_TOTAL_INPUT_CHANNEL - 1);
	SIGNAL s_conv_slider_conv_pipeline_kernel_en                : STD_LOGIC_VECTOR(0 TO G_TOTAL_INPUT_CHANNEL - 1);
	SIGNAL s_conv_slider_conv_pipeline_kernel_activation_matrix : STD_LOGIC_VECTOR(G_TOTAL_INPUT_CHANNEL * G_KERNEL_SIZE ** 2 * G_BIT_WIDTH - 1 DOWNTO 0);

	-- conv pipeline -> max pool pipeline
	SIGNAL s_conv_pipeline_pool_pipeline_kernel_complete          : STD_LOGIC_VECTOR(0 TO G_TOTAL_INPUT_CHANNEL - 1);
	SIGNAL s_conv_pipeline_pool_pipeline_kernel_en                : STD_LOGIC_VECTOR(0 TO G_TOTAL_INPUT_CHANNEL - 1);
	SIGNAL s_conv_pipeline_pool_pipeline_kernel_activation_matrix : STD_LOGIC_VECTOR(G_TOTAL_INPUT_CHANNEL * G_ACCUMULATOR_BIT_WIDTH - 1 DOWNTO 0);

	-- reduced control signals of the combining pipeline
	SIGNAL s_combine_kernel_en       : STD_LOGIC;
	SIGNAL s_combine_kernel_complete : STD_LOGIC;

	-- Base_addr register for accumulating the offset for the weights
	SIGNAL s_base_addr     : UNSIGNED(integer(ceil(log2(real(G_KERNEL_SIZE ** 2 * G_TOTAL_OUTPUT_CHANNEL)))) - 1 DOWNTO 0);
	SIGNAL s_base_addr_slv : STD_LOGIC_VECTOR(integer(ceil(log2(real(G_KERNEL_SIZE ** 2 * G_TOTAL_OUTPUT_CHANNEL)))) - 1 DOWNTO 0);

BEGIN

	o_pixel_complete       <= s_new_pixel_complete;
	o_pixel_output_channel <= std_logic_vector(s_current_output_channel);

	s_base_addr_slv <= std_logic_vector(s_base_addr);

	CHANNEL_CTRL_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN
				s_current_output_channel <= (OTHERS => '0');
				s_streaming_fifo_rd_en   <= '0';
				s_new_pixel_complete     <= '0';
				s_channel_reset          <= '1';
				s_base_addr              <= (OTHERS => '0');
			ELSE
				-- If Channel is finished and no rst is set, make a channel rst or finish computation
				IF s_channel_comp_complete = '1' AND s_channel_reset = '0' THEN
					IF s_current_output_channel < G_TOTAL_OUTPUT_CHANNEL - 1 THEN
						s_current_output_channel <= s_current_output_channel + 1;
						s_channel_reset          <= '1';
						-- Increment base addr by G_KERNEL_SIZE**2 to offset weights correctly
						s_base_addr <= s_base_addr + G_KERNEL_SIZE ** 2;
					ELSE
						-- This delays complete signal by one cycle! This would be an issue if new_valid_pixel could be '1' after channel_comp = '1'
						-- but this should never happen, to this is fine for now
						s_new_pixel_complete <= '1';
					END IF;

					-- don't read during rst (but this could also be omitted)
					s_streaming_fifo_rd_en <= '0';
				END IF;

				-- Always try to read from fifo, if reads are illegal, they are blocked by fifo itself
				IF s_channel_comp_complete = '0' AND s_channel_reset = '1' THEN
					s_channel_reset        <= '0';
					s_streaming_fifo_rd_en <= '1';
				END IF;
			END IF;
		END IF;

	END PROCESS CHANNEL_CTRL_PROC;

	PIPELINE_GEN : FOR i IN 0 TO G_TOTAL_INPUT_CHANNEL - 1 GENERATE

		STREAMING_FIFO_INST : ENTITY work.bram_streaming_fifo
			GENERIC MAP (
				G_BIT_WIDTH => G_BIT_WIDTH,
				G_DEPTH     => G_INPUT_WIDTH * G_INPUT_HEIGHT
			)
			PORT MAP (
				clk          => clk,
				rst          => rst,
				i_read_reset => s_channel_reset,
				i_wr_en      => i_valid_pixel,
				i_rd_en      => s_streaming_fifo_rd_en,
				o_full       => open,
				o_empty      => open,
				o_dout_valid => s_fifo_conv_pixel_valid(i),
				i_din        => i_pixel_stream((i + 1) * G_BIT_WIDTH - 1 DOWNTO i * G_BIT_WIDTH),
				o_dout       => s_fifo_conv_pixel_stream((i + 1) * G_BIT_WIDTH - 1 DOWNTO i * G_BIT_WIDTH)
			);

		CONV_SLIDER : ENTITY work.convolution_slider
			GENERIC MAP (
				G_BIT_WIDTH    => G_BIT_WIDTH,
				G_INPUT_WIDTH  => G_INPUT_WIDTH,
				G_INPUT_HEIGHT => G_INPUT_HEIGHT,
				G_KERNEL_SIZE  => G_KERNEL_SIZE
			)
			PORT MAP (
				clk                  => clk,
				rst                  => s_channel_reset,
				i_pixel_stream       => s_fifo_conv_pixel_stream((i + 1) * G_BIT_WIDTH - 1 DOWNTO i * G_BIT_WIDTH),
				i_valid_pixel        => s_fifo_conv_pixel_valid(i),
				o_kernel_complete    => s_conv_slider_conv_pipeline_kernel_complete(i),
				o_kernel_en          => s_conv_slider_conv_pipeline_kernel_en(i),
				o_kernel_activations => s_conv_slider_conv_pipeline_kernel_activation_matrix((i + 1) * G_KERNEL_SIZE ** 2 * G_BIT_WIDTH - 1 DOWNTO i * G_KERNEL_SIZE ** 2 * G_BIT_WIDTH)
			);

		CONV_PIPELINE_INST : ENTITY work.conv_pipeline
			GENERIC MAP (
				G_INPUT_AMOUNT         => G_KERNEL_SIZE ** 2,
				G_BIT_WIDTH            => G_BIT_WIDTH,
				G_INPUT_WIDTH          => G_INPUT_WIDTH - (G_KERNEL_SIZE - 1),
				G_INPUT_HEIGHT         => G_INPUT_HEIGHT - (G_KERNEL_SIZE - 1),
				G_KERNEL_SIZE          => G_KERNEL_SIZE,
				G_ENABLE_WEIGHTS       => 1,
				G_TOTAL_INPUT_CHANNEL  => G_TOTAL_INPUT_CHANNEL,
				G_TOTAL_OUTPUT_CHANNEL => G_TOTAL_OUTPUT_CHANNEL,
				-- important: this has to start from 1
				G_CURRENT_CHANNEL    => i + 1,
				G_INIT_TYPE          => 1,
				G_WEIGHT_PATH_PREFIX => G_WEIGHT_PATH_PREFIX,

				-- not used
				G_SCALE_ID        => G_SCALE_ID,
				G_SCALE_FILE_PATH => G_SCALE_FILE_PATH,

				G_ENABLE_CLIP_ADDER => 1,
				G_ENABLE_MUL_LINE   => 1,
				G_ENABLE_SHIFT      => 0,
				G_ENABLE_RELU       => 0,
				G_OUT_BIT_WIDTH     => G_ACCUMULATOR_BIT_WIDTH
			)
			PORT MAP (
				clk               => clk,
				rst               => s_channel_reset,
				i_activations     => s_conv_slider_conv_pipeline_kernel_activation_matrix((i + 1) * G_KERNEL_SIZE ** 2 * G_BIT_WIDTH - 1 DOWNTO i * G_KERNEL_SIZE ** 2 * G_BIT_WIDTH),
				i_kernel_en       => s_conv_slider_conv_pipeline_kernel_en(i),
				i_kernel_complete => s_conv_slider_conv_pipeline_kernel_complete(i),
				i_base_addr       => s_base_addr_slv,
				o_weights_valid   => open,
				o_pixel           => s_conv_pipeline_pool_pipeline_kernel_activation_matrix((i + 1) * G_ACCUMULATOR_BIT_WIDTH - 1 DOWNTO i * G_ACCUMULATOR_BIT_WIDTH),
				o_valid_pixel     => s_conv_pipeline_pool_pipeline_kernel_en(i),
				o_comp_complete   => s_conv_pipeline_pool_pipeline_kernel_complete(i)
			);

	END GENERATE PIPELINE_GEN;

	s_combine_kernel_en       <= f_or_reduce(s_conv_pipeline_pool_pipeline_kernel_en);
	s_combine_kernel_complete <= f_or_reduce(s_conv_pipeline_pool_pipeline_kernel_complete);

	PIPELINE_INST : ENTITY work.conv_pool_pipeline
		GENERIC MAP (
			G_BIT_WIDTH            => G_ACCUMULATOR_BIT_WIDTH,
			G_INPUT_AMOUNT         => G_TOTAL_INPUT_CHANNEL,
			G_INPUT_WIDTH          => G_INPUT_WIDTH - (G_KERNEL_SIZE - 1),
			G_INPUT_HEIGHT         => G_INPUT_HEIGHT - (G_KERNEL_SIZE - 1),
			G_KERNEL_SIZE          => 1,
			G_POOLING_SIZE         => G_POOLING_SIZE,
			G_ENABLE_WEIGHTS       => 0,
			G_TOTAL_INPUT_CHANNEL  => G_TOTAL_INPUT_CHANNEL,
			G_TOTAL_OUTPUT_CHANNEL => 1,
			G_CURRENT_CHANNEL      => 1,
			G_INIT_TYPE            => 0,
			G_WEIGHT_PATH_PREFIX   => "",
			G_SCALE_ID             => G_SCALE_ID,
			G_SCALE_FILE_PATH      => G_SCALE_FILE_PATH,
			G_SCALE_BIT_WIDTH      => G_BIT_WIDTH,
			G_ENABLE_CLIP_ADDER    => G_ENABLE_CLIP_ADDER,
			G_ENABLE_MUL_LINE      => 0,
			G_ENABLE_SHIFT         => 1,
			G_ENABLE_RELU          => 1,
			G_OUT_BIT_WIDTH        => G_BIT_WIDTH
		)
		PORT MAP (
			clk               => clk,
			rst               => s_channel_reset,
			i_activations     => s_conv_pipeline_pool_pipeline_kernel_activation_matrix,
			i_kernel_en       => s_combine_kernel_en,
			i_kernel_complete => s_combine_kernel_complete,
			i_base_addr       => open,
			o_weights_valid   => open,
			o_pixel           => o_pixels_stream,
			o_valid_pixel     => o_valid_pixel,
			o_comp_complete   => s_channel_comp_complete
		);

END ARCHITECTURE rtl;
