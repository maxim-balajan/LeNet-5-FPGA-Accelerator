LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

ENTITY dense_layer IS
	GENERIC (
		G_BIT_WIDTH     : NATURAL := 8;
		G_OUT_BIT_WIDTH : NATURAL := 24;
		-- weight_width == input_height
		G_MAX_WEIGHT_WIDTH  : NATURAL := 400;
		G_MAX_WEIGHT_HEIGHT : NATURAL := 120;
		--! row widths of the three dense layers
		G_WEIGHT_WIDTH_0 : NATURAL := 400;
		G_WEIGHT_WIDTH_1 : NATURAL := 120;
		G_WEIGHT_WIDTH_2 : NATURAL := 84;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING := "../data/output/dense_weights_row"
	);
	PORT (
		clk                    : IN STD_LOGIC;
		rst                    : IN STD_LOGIC;
		i_en                   : IN STD_LOGIC;
		i_actual_weight_width  : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_MAX_WEIGHT_WIDTH)))) DOWNTO 0);
		i_actual_weight_height : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_MAX_WEIGHT_HEIGHT)))) DOWNTO 0);
		i_vector               : IN STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		i_base_addr            : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_WEIGHT_WIDTH_0 + G_WEIGHT_WIDTH_1 + G_WEIGHT_WIDTH_2)))) - 1 DOWNTO 0);
		--! one result per MAC, MAC i occupies ((i + 1) * G_OUT_BIT_WIDTH - 1 downto i * G_OUT_BIT_WIDTH)
		o_results       : OUT STD_LOGIC_VECTOR(G_MAX_WEIGHT_HEIGHT * G_OUT_BIT_WIDTH - 1 DOWNTO 0);
		o_comp_complete : OUT STD_LOGIC
	);
END ENTITY dense_layer;

ARCHITECTURE rtl OF dense_layer IS

	SIGNAL s_weights      : STD_LOGIC_VECTOR(G_MAX_WEIGHT_HEIGHT * G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_bram_en_line : STD_LOGIC_VECTOR(0 TO G_MAX_WEIGHT_HEIGHT - 1);

BEGIN

	MV_UNIT_INST : ENTITY work.matrix_vector_unit
		GENERIC MAP (
			G_MAX_WEIGHT_WIDTH  => G_MAX_WEIGHT_WIDTH,
			G_MAX_WEIGHT_HEIGHT => G_MAX_WEIGHT_HEIGHT,
			G_BIT_WIDTH         => G_BIT_WIDTH,
			G_OUT_BIT_WIDTH     => G_OUT_BIT_WIDTH
		)
		PORT MAP (
			clk                    => clk,
			rst                    => rst,
			i_en                   => i_en,
			i_actual_weight_width  => i_actual_weight_width,
			i_actual_weight_height => i_actual_weight_height,
			i_weights              => s_weights,
			i_vector               => i_vector,
			o_bram_enable_line     => s_bram_en_line,
			o_results              => o_results,
			o_comp_complete        => o_comp_complete
		);

	MEM_INTER_CONNECT_INST : ENTITY work.matrix_vector_mem_interconnect
		GENERIC MAP (
			G_BIT_WIDTH          => G_BIT_WIDTH,
			G_MAX_WEIGHT_WIDTH   => G_MAX_WEIGHT_WIDTH,
			G_MAX_WEIGHT_HEIGHT  => G_MAX_WEIGHT_HEIGHT,
			G_WEIGHT_WIDTH_0     => G_WEIGHT_WIDTH_0,
			G_WEIGHT_WIDTH_1     => G_WEIGHT_WIDTH_1,
			G_WEIGHT_WIDTH_2     => G_WEIGHT_WIDTH_2,
			G_WEIGHT_PATH_PREFIX => G_WEIGHT_PATH_PREFIX
		)
		PORT MAP (
			clk                => clk,
			rst                => rst,
			i_bram_enable_line => s_bram_en_line,
			i_base_addr        => i_base_addr,
			o_weights          => s_weights
		);

END ARCHITECTURE rtl;
