LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

ENTITY lenet_accel IS
	GENERIC (
		--! general generics that are necessary
		G_BIT_WIDTH                   : NATURAL              := 8;
		G_ACCUMULATOR_BIT_WIDTH       : NATURAL              := 24;
		G_INPUT_WIDTH                 : NATURAL              := 32;
		G_INPUT_HEIGHT                : NATURAL              := 32;
		G_KERNEL_SIZE                 : NATURAL              := 5;
		G_POOLING_SIZE                : INTEGER RANGE 2 TO 2 := 2;
		G_ENABLE_CLIP_ADDER           : INTEGER RANGE 0 TO 1 := 1;
		G_TOTAL_INPUT_CHANNEL_CONV_1  : NATURAL              := 1;
		G_TOTAL_INPUT_CHANNEL_CONV_2  : NATURAL              := 6;
		G_TOTAL_OUTPUT_CHANNEL_CONV_2 : NATURAL              := 16;
		G_SCALE_FILE_PATH             : STRING               := "../data/scale_values.data";
		--! scale ids of the two convolutional layers
		G_CONV_SCALE_ID_0 : NATURAL := 1;
		G_CONV_SCALE_ID_1 : NATURAL := 2;
		--! scale ids of the three dense layers
		G_DENSE_SCALE_ID_0 : NATURAL := 3;
		G_DENSE_SCALE_ID_1 : NATURAL := 4;
		G_DENSE_SCALE_ID_2 : NATURAL := 5;
		--! dimensions of the three dense layers
		G_DENSE_WEIGHT_WIDTH_0  : NATURAL := 400;
		G_DENSE_WEIGHT_WIDTH_1  : NATURAL := 120;
		G_DENSE_WEIGHT_WIDTH_2  : NATURAL := 84;
		G_DENSE_WEIGHT_HEIGHT_0 : NATURAL := 120;
		G_DENSE_WEIGHT_HEIGHT_1 : NATURAL := 84;
		G_DENSE_WEIGHT_HEIGHT_2 : NATURAL := 10;
		--! prefixes of the BRAM files generated by data/generate_bram_data.py
		G_CONV_WEIGHT_PREFIX_0 : STRING := "../data/output/conv_1_weights_ch";
		G_CONV_WEIGHT_PREFIX_1 : STRING := "../data/output/conv_2_weights_ch";
		G_DENSE_WEIGHT_PREFIX  : STRING := "../data/output/dense_weights_row"
	);
	PORT (
		clk             : IN STD_LOGIC;
		rst             : IN STD_LOGIC;
		i_pixel_stream  : IN STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		i_valid_pixel   : IN STD_LOGIC;
		o_image_label   : OUT STD_LOGIC_VECTOR(integer(ceil(log2(real(G_DENSE_WEIGHT_HEIGHT_2)))) - 1 DOWNTO 0);
		o_comp_complete : OUT STD_LOGIC
	);
END ENTITY lenet_accel;

ARCHITECTURE rtl OF lenet_accel IS

	-- Signals between Convolution and Dense-Layer
	SIGNAL s_conv_to_dense_stream   : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_conv_to_dense_valid    : STD_LOGIC;
	SIGNAL s_conv_to_dense_complete : STD_LOGIC;
	-- once the convolutions report completion no further pixel may enter the dense layers
	SIGNAL s_conv_to_dense_en : STD_LOGIC;

	-- Signals between Dense-Layer and Argmax-Unit
	SIGNAL s_dense_to_argmax_stream : STD_LOGIC_VECTOR(G_DENSE_WEIGHT_HEIGHT_2 * G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_dense_complete         : STD_LOGIC;

BEGIN

	s_conv_to_dense_en <= s_conv_to_dense_valid AND not s_conv_to_dense_complete;

	CONV_COMB_INST : ENTITY work.conv_combined
		GENERIC MAP (
			G_BIT_WIDTH                   => G_BIT_WIDTH,
			G_ACCUMULATOR_BIT_WIDTH       => G_ACCUMULATOR_BIT_WIDTH,
			G_INPUT_WIDTH                 => G_INPUT_WIDTH,
			G_INPUT_HEIGHT                => G_INPUT_HEIGHT,
			G_KERNEL_SIZE                 => G_KERNEL_SIZE,
			G_POOLING_SIZE                => G_POOLING_SIZE,
			G_ENABLE_CLIP_ADDER           => G_ENABLE_CLIP_ADDER,
			G_TOTAL_INPUT_CHANNEL_CONV_1  => G_TOTAL_INPUT_CHANNEL_CONV_1,
			G_TOTAL_INPUT_CHANNEL_CONV_2  => G_TOTAL_INPUT_CHANNEL_CONV_2,
			G_TOTAL_OUTPUT_CHANNEL_CONV_2 => G_TOTAL_OUTPUT_CHANNEL_CONV_2,
			G_WEIGHT_PREFIX_CONV_1        => G_CONV_WEIGHT_PREFIX_0,
			G_WEIGHT_PREFIX_CONV_2        => G_CONV_WEIGHT_PREFIX_1,
			G_SCALE_ID_CONV_1             => G_CONV_SCALE_ID_0,
			G_SCALE_ID_CONV_2             => G_CONV_SCALE_ID_1,
			G_SCALE_FILE_PATH             => G_SCALE_FILE_PATH
		)
		PORT MAP (
			clk              => clk,
			rst              => rst,
			i_pixel_stream   => i_pixel_stream,
			i_valid_pixel    => i_valid_pixel,
			o_pixel_stream   => s_conv_to_dense_stream,
			o_valid_pixel    => s_conv_to_dense_valid,
			o_pixel_complete => s_conv_to_dense_complete
		);

	DENSE_LAYER_COMB_INST : ENTITY work.dense_layer_combined
		GENERIC MAP (
			G_BIT_WIDTH          => G_BIT_WIDTH,
			G_MAX_WEIGHT_WIDTH   => G_DENSE_WEIGHT_WIDTH_0,
			G_MAX_WEIGHT_HEIGHT  => G_DENSE_WEIGHT_HEIGHT_0,
			G_SCALE_FILE_PATH    => G_SCALE_FILE_PATH,
			G_SCALE_ID_0         => G_DENSE_SCALE_ID_0,
			G_SCALE_ID_1         => G_DENSE_SCALE_ID_1,
			G_SCALE_ID_2         => G_DENSE_SCALE_ID_2,
			G_WEIGHT_WIDTH_0     => G_DENSE_WEIGHT_WIDTH_0,
			G_WEIGHT_WIDTH_1     => G_DENSE_WEIGHT_WIDTH_1,
			G_WEIGHT_WIDTH_2     => G_DENSE_WEIGHT_WIDTH_2,
			G_WEIGHT_HEIGHT_0    => G_DENSE_WEIGHT_HEIGHT_0,
			G_WEIGHT_HEIGHT_1    => G_DENSE_WEIGHT_HEIGHT_1,
			G_WEIGHT_HEIGHT_2    => G_DENSE_WEIGHT_HEIGHT_2,
			G_WEIGHT_PATH_PREFIX => G_DENSE_WEIGHT_PREFIX
		)
		PORT MAP (
			clk             => clk,
			rst             => rst,
			i_en            => s_conv_to_dense_en,
			i_vector        => s_conv_to_dense_stream,
			o_results       => s_dense_to_argmax_stream,
			o_comp_complete => s_dense_complete
		);

	ARGMAX_INST : ENTITY work.comparator_tree_unit
		GENERIC MAP (
			G_BIT_WIDTH => G_BIT_WIDTH,
			-- one register per tree step, which matches the latency of the old pipeline
			G_INIT_PIPELINE_STEPS => 1,
			G_INPUT_AMOUNT        => G_DENSE_WEIGHT_HEIGHT_2,
			G_CONTROL_AMOUNT      => 1,
			-- the clipped dense layer results are signed and can be negative
			G_SIGNED       => 1,
			G_ENABLE_INDEX => 1
		)
		PORT MAP (
			clk => clk,
			rst => rst,
			--
			i_en => '1',
			--
			i_vec0 => s_dense_to_argmax_stream,
			--
			i_control_signals(0) => s_dense_complete,
			--
			o_index              => o_image_label,
			o_control_signals(0) => o_comp_complete
		);

END ARCHITECTURE rtl;
