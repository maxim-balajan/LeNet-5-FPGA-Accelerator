LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;
USE work.libmemory.ALL;

ENTITY conv_pipeline IS
	GENERIC (
		--! general generics that are necessary
		G_BIT_WIDTH    : NATURAL := 8;
		G_INPUT_WIDTH  : NATURAL := 32;
		G_INPUT_HEIGHT : NATURAL := 32;
		G_KERNEL_SIZE  : NATURAL := 5;

		--! this value indicates how many values are streamed into the pipeline. If G_ENABLE_WEIGHTS = 1 this should probably be G_KERNEL_SIZE**2
		--! otherwise it could also be a totally different value (e.g. 6)
		G_INPUT_AMOUNT   : NATURAL              := 25;
		G_ENABLE_WEIGHTS : INTEGER RANGE 0 TO 1 := 1;

		--! generics used for initializing BRAM Weight Memory
		G_TOTAL_INPUT_CHANNEL  : NATURAL              := 1;
		G_TOTAL_OUTPUT_CHANNEL : NATURAL              := 1;
		G_CURRENT_CHANNEL      : NATURAL              := 1;
		G_INIT_TYPE            : INTEGER RANGE 0 TO 1 := 0;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING  := "../data/output/conv_1_weights_ch";
		G_SCALE_ID           : NATURAL := 1;
		G_SCALE_FILE_PATH    : STRING  := "../data/scale_values.data";
		--! has to be set to G_BIT_WIDTH by the instantiation if that is not 8
		G_SCALE_BIT_WIDTH : NATURAL := 8;

		--! generics used for convolution_comp_unit
		G_ENABLE_CLIP_ADDER : INTEGER RANGE 0 TO 1 := 1;
		G_ENABLE_MUL_LINE   : INTEGER RANGE 0 TO 1 := 1;
		G_ENABLE_SHIFT      : INTEGER RANGE 0 TO 1 := 1;
		G_ENABLE_RELU       : INTEGER RANGE 0 TO 1 := 1;
		--! at most 3 * G_BIT_WIDTH when G_ENABLE_MUL_LINE = 1, otherwise at most G_BIT_WIDTH
		G_OUT_BIT_WIDTH : NATURAL := 8
	);
	PORT (
		clk : IN STD_LOGIC;
		rst : IN STD_LOGIC;
		--! G_INPUT_AMOUNT values, element i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		i_activations     : IN STD_LOGIC_VECTOR(G_INPUT_AMOUNT * G_BIT_WIDTH - 1 DOWNTO 0);
		i_kernel_en       : IN STD_LOGIC;
		i_kernel_complete : IN STD_LOGIC;
		i_base_addr       : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_INPUT_AMOUNT * G_TOTAL_INPUT_CHANNEL ** (1 - G_INIT_TYPE) * G_TOTAL_OUTPUT_CHANNEL ** (G_INIT_TYPE))))) - 1 DOWNTO 0) := (OTHERS => '0');
		o_weights_valid   : OUT STD_LOGIC;
		o_pixel           : OUT STD_LOGIC_VECTOR(G_OUT_BIT_WIDTH - 1 DOWNTO 0);
		o_valid_pixel     : OUT STD_LOGIC;
		o_comp_complete   : OUT STD_LOGIC
	);
END ENTITY conv_pipeline;

ARCHITECTURE rtl OF conv_pipeline IS

	-- Depth of the weight memory is purely dependent on the init type
	CONSTANT C_WEIGHT_DEPTH : NATURAL := G_INPUT_AMOUNT * G_TOTAL_INPUT_CHANNEL ** (1 - G_INIT_TYPE) * G_TOTAL_OUTPUT_CHANNEL ** (G_INIT_TYPE);

	-- Value used for scaling in the Conv_Comp_Unit
	CONSTANT C_SCALE_VALUE : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0) := read_scale_value(G_SCALE_FILE_PATH, G_BIT_WIDTH, G_SCALE_BIT_WIDTH, G_SCALE_ID, G_BIT_WIDTH);

	SIGNAL s_weights : STD_LOGIC_VECTOR(G_INPUT_AMOUNT * G_BIT_WIDTH - 1 DOWNTO 0);

	-- The tree carries the two control signals of this unit through its pipeline.
	-- Bit 0 is the kernel enable, bit 1 the completion flag.
	CONSTANT C_CONTROL_AMOUNT : NATURAL := 2;

	SIGNAL s_control_in  : STD_LOGIC_VECTOR(C_CONTROL_AMOUNT - 1 DOWNTO 0);
	SIGNAL s_control_out : STD_LOGIC_VECTOR(C_CONTROL_AMOUNT - 1 DOWNTO 0);

BEGIN

	s_control_in(0) <= i_kernel_en;
	s_control_in(1) <= i_kernel_complete;

	-- For second convolution weights should be disabled because there wont be a multiplication line for the combining pipeline

	WEIGHT_GEN : IF G_ENABLE_WEIGHTS = 1 GENERATE

		WEIGHT_MEM : ENTITY work.conv_weight_memory
			GENERIC MAP (
				G_BIT_WIDTH    => G_BIT_WIDTH,
				G_INPUT_AMOUNT => G_INPUT_AMOUNT,
				G_DEPTH        => C_WEIGHT_DEPTH,
				-- the generated files are numbered from 0, current_channel starts at 1
				G_DATA_FILE_PATH => bram_path(G_WEIGHT_PATH_PREFIX, G_CURRENT_CHANNEL - 1)
			)
			PORT MAP (
				clk         => clk,
				rst         => rst,
				i_base_addr => i_base_addr,
				o_mem_valid => o_weights_valid,
				o_weights   => s_weights
			);

	END GENERATE WEIGHT_GEN;

	NO_WEIGHT_GEN : IF G_ENABLE_WEIGHTS = 0 GENERATE
		o_weights_valid <= '0';
		s_weights       <= (OTHERS => '0');
	END GENERATE NO_WEIGHT_GEN;

	-- Convolution: multiply activations with weights, sum them up, then shift, clip and ReLU
	ADDER_TREE_INST : ENTITY work.adder_tree_unit
		GENERIC MAP (
			G_BIT_WIDTH => G_BIT_WIDTH,
			-- widen the accumulator to 3 * G_BIT_WIDTH when the multiplication line is used
			G_BIT_WIDTH_EXTENDED => G_ENABLE_MUL_LINE * G_BIT_WIDTH,
			G_OUT_BIT_WIDTH      => G_OUT_BIT_WIDTH,
			-- one register per tree step
			G_INIT_PIPELINE_STEPS => 1,
			G_INPUT_AMOUNT        => G_INPUT_AMOUNT,
			G_CONTROL_AMOUNT      => C_CONTROL_AMOUNT,
			G_ENABLE_MUL_LINE     => G_ENABLE_MUL_LINE,
			G_CLIP_ADDER          => G_ENABLE_CLIP_ADDER,
			G_ENABLE_SHIFT        => G_ENABLE_SHIFT,
			G_ENABLE_RELU         => G_ENABLE_RELU
		)
		PORT MAP (
			clk => clk,
			rst => rst,
			--
			i_en => '1',
			--
			i_vec0  => i_activations,
			i_vec1  => s_weights,
			i_shamt => C_SCALE_VALUE,
			--
			i_control_signals => s_control_in,
			--
			o_vec             => o_pixel,
			o_control_signals => s_control_out
		);

	o_valid_pixel   <= s_control_out(0);
	o_comp_complete <= s_control_out(1);

END ARCHITECTURE rtl;
