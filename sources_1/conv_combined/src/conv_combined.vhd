LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;

ENTITY conv_combined IS
	GENERIC (
		--! general generics that are necessary
		G_BIT_WIDTH             : NATURAL              := 8;
		G_ACCUMULATOR_BIT_WIDTH : NATURAL              := 24;
		G_INPUT_WIDTH           : NATURAL              := 32;
		G_INPUT_HEIGHT          : NATURAL              := 32;
		G_KERNEL_SIZE           : NATURAL              := 5;
		G_POOLING_SIZE          : INTEGER RANGE 2 TO 2 := 2;
		G_ENABLE_CLIP_ADDER     : INTEGER RANGE 0 TO 1 := 1;

		--! generics used for initializing BRAM Weight Memory
		G_TOTAL_INPUT_CHANNEL_CONV_1  : NATURAL := 1;
		G_TOTAL_INPUT_CHANNEL_CONV_2  : NATURAL := 6;
		G_TOTAL_OUTPUT_CHANNEL_CONV_2 : NATURAL := 16;
		--! prefixes of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PREFIX_CONV_1 : STRING  := "../data/output/conv_1_weights_ch";
		G_WEIGHT_PREFIX_CONV_2 : STRING  := "../data/output/conv_2_weights_ch";
		G_SCALE_ID_CONV_1      : NATURAL := 1;
		G_SCALE_ID_CONV_2      : NATURAL := 2;
		G_SCALE_FILE_PATH      : STRING  := "../data/scale_values.data"
	);
	PORT (
		clk              : IN STD_LOGIC;
		rst              : IN STD_LOGIC;
		i_pixel_stream   : IN STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		i_valid_pixel    : IN STD_LOGIC;
		o_pixel_stream   : OUT STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		o_valid_pixel    : OUT STD_LOGIC;
		o_pixel_complete : OUT STD_LOGIC
	);
END ENTITY conv_combined;

ARCHITECTURE rtl OF conv_combined IS

	SIGNAL s_intermediate_pixel_stream   : STD_LOGIC_VECTOR(G_TOTAL_INPUT_CHANNEL_CONV_2 * G_BIT_WIDTH - 1 DOWNTO 0);
	SIGNAL s_intermediate_valid_pixel    : STD_LOGIC;
	SIGNAL s_intermediate_pixel_complete : STD_LOGIC;
	-- once the first convolution reports completion no further pixel may enter the second one
	SIGNAL s_intermediate_valid_gated : STD_LOGIC;

BEGIN

	s_intermediate_valid_gated <= s_intermediate_valid_pixel AND not s_intermediate_pixel_complete;

	CONV_PAR_INST : ENTITY work.conv_par
		GENERIC MAP (
			G_BIT_WIDTH            => G_BIT_WIDTH,
			G_INPUT_WIDTH          => G_INPUT_WIDTH,
			G_INPUT_HEIGHT         => G_INPUT_HEIGHT,
			G_KERNEL_SIZE          => G_KERNEL_SIZE,
			G_POOLING_SIZE         => G_POOLING_SIZE,
			G_ENABLE_CLIP_ADDER    => G_ENABLE_CLIP_ADDER,
			G_TOTAL_INPUT_CHANNEL  => G_TOTAL_INPUT_CHANNEL_CONV_1,
			G_TOTAL_OUTPUT_CHANNEL => G_TOTAL_INPUT_CHANNEL_CONV_2,
			G_WEIGHT_PATH_PREFIX   => G_WEIGHT_PREFIX_CONV_1,
			G_SCALE_ID             => G_SCALE_ID_CONV_1,
			G_SCALE_FILE_PATH      => G_SCALE_FILE_PATH
		)
		PORT MAP (
			clk              => clk,
			rst              => rst,
			i_pixel_stream   => i_pixel_stream,
			i_valid_pixel    => i_valid_pixel,
			o_pixels_stream  => s_intermediate_pixel_stream,
			o_valid_pixel    => s_intermediate_valid_pixel,
			o_pixel_complete => s_intermediate_pixel_complete
		);

	CONV_SEQ_INST : ENTITY work.conv_seq
		GENERIC MAP (
			G_BIT_WIDTH             => G_BIT_WIDTH,
			G_ACCUMULATOR_BIT_WIDTH => G_ACCUMULATOR_BIT_WIDTH,
			G_INPUT_WIDTH           => (G_INPUT_WIDTH - G_KERNEL_SIZE + 1) / 2,
			G_INPUT_HEIGHT          => (G_INPUT_HEIGHT - G_KERNEL_SIZE + 1) / 2,
			G_KERNEL_SIZE           => G_KERNEL_SIZE,
			G_POOLING_SIZE          => G_POOLING_SIZE,
			G_ENABLE_CLIP_ADDER     => G_ENABLE_CLIP_ADDER,
			G_TOTAL_INPUT_CHANNEL   => G_TOTAL_INPUT_CHANNEL_CONV_2,
			G_TOTAL_OUTPUT_CHANNEL  => G_TOTAL_OUTPUT_CHANNEL_CONV_2,
			G_WEIGHT_PATH_PREFIX    => G_WEIGHT_PREFIX_CONV_2,
			G_SCALE_ID              => G_SCALE_ID_CONV_2,
			G_SCALE_FILE_PATH       => G_SCALE_FILE_PATH
		)
		PORT MAP (
			clk                    => clk,
			rst                    => rst,
			i_pixel_stream         => s_intermediate_pixel_stream,
			i_valid_pixel          => s_intermediate_valid_gated,
			o_pixels_stream        => o_pixel_stream,
			o_valid_pixel          => o_valid_pixel,
			o_pixel_complete       => o_pixel_complete,
			o_pixel_output_channel => open
		);

END ARCHITECTURE rtl;
