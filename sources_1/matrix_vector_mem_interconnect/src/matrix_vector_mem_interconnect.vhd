LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;
USE work.libmemory.ALL;

--! Weight memory of the Matrix-Vector-Unit.
--!
--! One BRAM tile holds one weight row of every one of the three dense layers, stored
--! back to back. data/generate_bram_data.py builds those files, including the zero
--! padding for the tiles of rows that the smaller layers do not reach.
--!
--! Every MAC is delayed one cycle more than the previous one, so the addresses are
--! shifted through a register chain instead of being accumulated per tile.

ENTITY matrix_vector_mem_interconnect IS
	GENERIC (
		G_BIT_WIDTH : NATURAL := 8;
		--! G_MAX_WEIGHT_{WIDTH | HEIGHT} \geq max(G_WEIGHT_{WIDTH | HEIGHT}_*), otherwise code could break
		G_MAX_WEIGHT_WIDTH  : NATURAL := 400;
		G_MAX_WEIGHT_HEIGHT : NATURAL := 120;
		--! row widths of the three dense layers, they add up to the depth of one tile
		G_WEIGHT_WIDTH_0 : NATURAL := 400;
		G_WEIGHT_WIDTH_1 : NATURAL := 120;
		G_WEIGHT_WIDTH_2 : NATURAL := 84;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING := "../data/output/dense_weights_row"
	);
	PORT (
		clk                : IN STD_LOGIC;
		rst                : IN STD_LOGIC;
		i_bram_enable_line : IN STD_LOGIC_VECTOR(0 TO G_MAX_WEIGHT_HEIGHT - 1);
		i_base_addr        : IN STD_LOGIC_VECTOR(integer(ceil(log2(real(G_WEIGHT_WIDTH_0 + G_WEIGHT_WIDTH_1 + G_WEIGHT_WIDTH_2)))) - 1 DOWNTO 0);
		--! one weight per MAC, MAC i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		o_weights : OUT STD_LOGIC_VECTOR(G_MAX_WEIGHT_HEIGHT * G_BIT_WIDTH - 1 DOWNTO 0)
	);
END ENTITY matrix_vector_mem_interconnect;

ARCHITECTURE rtl OF matrix_vector_mem_interconnect IS

	--! Total depth of one BRAM tile
	CONSTANT C_TOTAL_WIDTH : NATURAL := G_WEIGHT_WIDTH_0 + G_WEIGHT_WIDTH_1 + G_WEIGHT_WIDTH_2;
	CONSTANT C_ADDR_WIDTH  : NATURAL := integer(ceil(log2(real(C_TOTAL_WIDTH))));

	TYPE t_addr_line IS ARRAY(0 TO G_MAX_WEIGHT_HEIGHT - 1) OF STD_LOGIC_VECTOR(C_ADDR_WIDTH - 1 DOWNTO 0);

	SIGNAL s_addr_line : t_addr_line;

	SIGNAL s_din : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);

BEGIN

	s_din <= (OTHERS => '0');

	-- This process sets the base addr and also shifts all values through the chained registers
	ADDR_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN
				s_addr_line                  <= (OTHERS => (OTHERS => '0'));
				s_addr_line(s_addr_line'low) <= i_base_addr;
			ELSE
				-- Set start of enable pipeline
				IF i_bram_enable_line(i_bram_enable_line'LOW) = '1' THEN
					-- This is to prevent OOB errors
					IF unsigned(s_addr_line(s_addr_line'LOW)) >= C_TOTAL_WIDTH - 1 THEN
						s_addr_line(s_addr_line'low) <= (OTHERS => '0');
					ELSE
						s_addr_line(s_addr_line'low) <= std_logic_vector(unsigned(s_addr_line(s_addr_line'LOW)) + 1);
					END IF;
				END IF;
				-- Shift values
				s_addr_line(s_addr_line'low + 1 to s_addr_line'high) <= s_addr_line(s_addr_line'LOW TO s_addr_line'HIGH - 1);
			END IF;
		END IF;

	END PROCESS ADDR_PROC;

	BRAM_GEN : FOR i IN 0 TO G_MAX_WEIGHT_HEIGHT - 1 GENERATE

		BRAM_INST : ENTITY work.bram_single_port
			GENERIC MAP (
				G_BIT_WIDTH => G_BIT_WIDTH,
				G_DEPTH     => C_TOTAL_WIDTH,
				-- row i of all three dense layers, already concatenated by the generator
				G_DATA_FILE_PATH => bram_path(G_WEIGHT_PATH_PREFIX, i)
			)
			PORT MAP (
				clk     => clk,
				i_rd_en => i_bram_enable_line(i),
				i_wr_en => '0',
				i_addr  => s_addr_line(i),
				i_din   => s_din,
				o_dout  => o_weights((i + 1) * G_BIT_WIDTH - 1 DOWNTO i * G_BIT_WIDTH)
			);

	END GENERATE BRAM_GEN;

END ARCHITECTURE rtl;
