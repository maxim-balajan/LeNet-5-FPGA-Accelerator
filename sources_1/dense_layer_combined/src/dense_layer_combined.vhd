LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;
USE ieee.math_real.ALL;
USE work.libmemory.ALL;

--! Runs the three fully connected layers one after the other on a single
--! Matrix-Vector-Unit. The intermediate results are kept unshifted in registers and are
--! only shifted and clipped when they are streamed back into the unit for the next
--! iteration, so that only one shifter and one clipper are needed.

ENTITY dense_layer_combined IS
	GENERIC (
		G_BIT_WIDTH : NATURAL := 8;
		-- weight_width == input_height
		G_MAX_WEIGHT_WIDTH  : NATURAL := 400;
		G_MAX_WEIGHT_HEIGHT : NATURAL := 120;
		G_SCALE_FILE_PATH   : STRING  := "../data/scale_values.data";
		--! scale ids and dimensions of the three dense layers
		G_SCALE_ID_0      : NATURAL := 3;
		G_SCALE_ID_1      : NATURAL := 4;
		G_SCALE_ID_2      : NATURAL := 5;
		G_WEIGHT_WIDTH_0  : NATURAL := 400;
		G_WEIGHT_WIDTH_1  : NATURAL := 120;
		G_WEIGHT_WIDTH_2  : NATURAL := 84;
		G_WEIGHT_HEIGHT_0 : NATURAL := 120;
		G_WEIGHT_HEIGHT_1 : NATURAL := 84;
		G_WEIGHT_HEIGHT_2 : NATURAL := 10;
		--! prefix of the BRAM files generated by data/generate_bram_data.py
		G_WEIGHT_PATH_PREFIX : STRING := "../data/output/dense_weights_row"
	);
	PORT (
		clk      : IN STD_LOGIC;
		rst      : IN STD_LOGIC;
		i_en     : IN STD_LOGIC;
		i_vector : IN STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
		--! the G_WEIGHT_HEIGHT_2 results, element i occupies ((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH)
		o_results       : OUT STD_LOGIC_VECTOR(G_WEIGHT_HEIGHT_2 * G_BIT_WIDTH - 1 DOWNTO 0);
		o_comp_complete : OUT STD_LOGIC
	);
END ENTITY dense_layer_combined;

ARCHITECTURE rtl OF dense_layer_combined IS

	--------------------------------------
	-- CONSTANTs and TYPEs
	--------------------------------------

	--! Amount of fully connected layers that are computed in series
	CONSTANT C_ITERATION_AMOUNT : NATURAL := 3;

	CONSTANT C_TOTAL_WIDTH : NATURAL := G_WEIGHT_WIDTH_0 + G_WEIGHT_WIDTH_1 + G_WEIGHT_WIDTH_2;
	CONSTANT C_ADDR_WIDTH  : NATURAL := integer(ceil(log2(real(C_TOTAL_WIDTH))));

	--! Width of one unshifted intermediate result
	CONSTANT C_RESULT_BIT_WIDTH : NATURAL := 3 * G_BIT_WIDTH;

	TYPE t_natural_array IS ARRAY(0 TO C_ITERATION_AMOUNT - 1) OF NATURAL;

	TYPE t_scale_array IS ARRAY(0 TO C_ITERATION_AMOUNT - 1) OF STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);

	TYPE t_base_addr_array IS ARRAY(0 TO C_ITERATION_AMOUNT - 1) OF STD_LOGIC_VECTOR(C_ADDR_WIDTH - 1 DOWNTO 0);

	TYPE t_result_array IS ARRAY(0 TO G_MAX_WEIGHT_HEIGHT - 1) OF STD_LOGIC_VECTOR(C_RESULT_BIT_WIDTH - 1 DOWNTO 0);

	TYPE t_shifted_input_array IS ARRAY(0 TO C_ITERATION_AMOUNT - 1) OF STD_LOGIC_VECTOR(C_RESULT_BIT_WIDTH - 1 DOWNTO 0);

	TYPE t_solution_array IS ARRAY(0 TO G_WEIGHT_HEIGHT_2 - 1) OF STD_LOGIC_VECTOR(C_RESULT_BIT_WIDTH - 1 DOWNTO 0);

	TYPE t_clipped_array IS ARRAY(0 TO G_WEIGHT_HEIGHT_2 - 1) OF STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);

	CONSTANT C_WEIGHT_WIDTHS  : t_natural_array := (G_WEIGHT_WIDTH_0, G_WEIGHT_WIDTH_1, G_WEIGHT_WIDTH_2);
	CONSTANT C_WEIGHT_HEIGHTS : t_natural_array := (G_WEIGHT_HEIGHT_0, G_WEIGHT_HEIGHT_1, G_WEIGHT_HEIGHT_2);

	--------------------------------------
	-- FUNCTIONs
	--------------------------------------

	--! This function retrieves all base_addresses necessary for computation

	FUNCTION f_get_base_addr RETURN t_base_addr_array IS

		VARIABLE tmp : t_base_addr_array;
		VARIABLE sum : NATURAL := 0;

	BEGIN

		FOR i IN tmp'RANGE LOOP

			tmp(i) := std_logic_vector(to_unsigned(sum, C_ADDR_WIDTH));
			sum    := sum + C_WEIGHT_WIDTHS(i);

		END LOOP;

		RETURN tmp;

	END FUNCTION f_get_base_addr;

	--! This function retrieves all necessary scale values

	IMPURE FUNCTION f_get_scale_values RETURN t_scale_array IS

		VARIABLE tmp        : t_scale_array;
		VARIABLE v_shift_id : t_natural_array := (G_SCALE_ID_0, G_SCALE_ID_1, G_SCALE_ID_2);

	BEGIN

		FOR i IN tmp'RANGE LOOP

			tmp(i) := read_scale_value(G_SCALE_FILE_PATH, G_BIT_WIDTH, G_BIT_WIDTH, v_shift_id(i), G_BIT_WIDTH);

		END LOOP;

		RETURN tmp;

	END FUNCTION f_get_scale_values;

	-- Constants for scales and base_addresses
	CONSTANT C_SCALE_VALUES : t_scale_array     := f_get_scale_values;
	CONSTANT C_BASE_ADDR    : t_base_addr_array := f_get_base_addr;

	--------------------------------------
	-- SIGNALs
	--------------------------------------

	-- Counter to check which dense iteration we are on
	SIGNAL s_iteration_count : UNSIGNED(integer(ceil(log2(real(C_ITERATION_AMOUNT)))) DOWNTO 0);
	-- This signal is for the temporary rst of the dense layer unit
	SIGNAL s_iteration_reset : STD_LOGIC;
	-- This signal indicates if a dense_layer has finished
	SIGNAL s_tmp_complete : STD_LOGIC;
	-- This signal stores the temporary results in order to stream it back to the input of the dense layer
	SIGNAL s_tmp_results              : t_result_array;
	SIGNAL s_tmp_results_read_pointer : UNSIGNED(integer(ceil(log2(real(G_MAX_WEIGHT_HEIGHT)))) DOWNTO 0);

	SIGNAL s_en : STD_LOGIC;

	SIGNAL s_comp_complete : STD_LOGIC;
	SIGNAL s_results       : STD_LOGIC_VECTOR(G_MAX_WEIGHT_HEIGHT * C_RESULT_BIT_WIDTH - 1 DOWNTO 0);

	-- Signals for pipelining input
	SIGNAL s_shifted_input_en : STD_LOGIC;
	SIGNAL s_sliced_input_en  : STD_LOGIC;
	SIGNAL s_sliced_input     : STD_LOGIC_VECTOR(C_RESULT_BIT_WIDTH - 1 DOWNTO 0);
	-- This signal stores all possible shifts of s_input
	SIGNAL s_shifted_input : t_shifted_input_array;
	-- This signal is feed into the dense layer
	SIGNAL s_input : STD_LOGIC_VECTOR(G_BIT_WIDTH - 1 DOWNTO 0);
	-- Signals for pipelining output
	SIGNAL s_shifted_en : STD_LOGIC;
	SIGNAL s_clipped_en : STD_LOGIC;
	-- This signal always computes the last shift of the first G_WEIGHT_HEIGHT_2 values
	SIGNAL s_shifted_solutions : t_solution_array;
	-- This signal contains the clipped version of s_shifted_solutions
	SIGNAL s_clipped_solutions : t_clipped_array;

	-- Registered generics that have to be indexed with the current iteration
	SIGNAL s_actual_weight_width  : STD_LOGIC_VECTOR(integer(ceil(log2(real(G_MAX_WEIGHT_WIDTH)))) DOWNTO 0);
	SIGNAL s_actual_weight_height : STD_LOGIC_VECTOR(integer(ceil(log2(real(G_MAX_WEIGHT_HEIGHT)))) DOWNTO 0);
	SIGNAL s_base_addr            : STD_LOGIC_VECTOR(C_ADDR_WIDTH - 1 DOWNTO 0);

BEGIN

	-- Select the parameters of the fully connected layer that is currently computed
	s_actual_weight_width  <= std_logic_vector(to_unsigned(C_WEIGHT_WIDTHS(to_integer(s_iteration_count)), s_actual_weight_width'LENGTH));
	s_actual_weight_height <= std_logic_vector(to_unsigned(C_WEIGHT_HEIGHTS(to_integer(s_iteration_count)), s_actual_weight_height'LENGTH));
	s_base_addr            <= C_BASE_ADDR(to_integer(s_iteration_count));

	CONTROL_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN
				s_iteration_count          <= (OTHERS => '0');
				s_iteration_reset          <= '1';
				s_input                    <= (OTHERS => '0');
				s_en                       <= '0';
				s_tmp_results_read_pointer <= (OTHERS => '0');
				s_comp_complete            <= '0';
			ELSE
				-- always set iteration rst to 0 for safety
				s_iteration_reset <= '0';
				-- Only do something while the iteration is not resetting
				IF s_iteration_reset /= '1' THEN
					-- if iteration is finished, then increase count and rst the dense layer unit
					IF s_tmp_complete = '1' THEN
						-- If all layers have been computed, finish calculation
						IF s_iteration_count >= C_ITERATION_AMOUNT - 1 THEN
							s_comp_complete <= '1';
						ELSE
							s_iteration_count          <= s_iteration_count + 1;
							s_iteration_reset          <= '1';
							s_en                       <= '0';
							s_tmp_results_read_pointer <= (OTHERS => '0');
						END IF;
					ELSIF s_iteration_count = 0 THEN
						s_input <= i_vector;
						s_en    <= i_en;
					ELSE
						-- Clip values that are streamed into mv_unit
						IF signed(s_shifted_input(to_integer(s_iteration_count) - 1)) > 2 ** (G_BIT_WIDTH - 1) - 1 THEN
							s_input <= std_logic_vector(to_signed(2 ** (G_BIT_WIDTH - 1) - 1, s_input'LENGTH));
						ELSIF signed(s_shifted_input(to_integer(s_iteration_count) - 1)) < - 2 ** (G_BIT_WIDTH - 1) THEN
							s_input <= std_logic_vector(to_signed(- 2 ** (G_BIT_WIDTH - 1), s_input'LENGTH));
						ELSE
							s_input <= s_shifted_input(to_integer(s_iteration_count) - 1)(G_BIT_WIDTH - 1 DOWNTO 0);
						END IF;
						s_en <= s_shifted_input_en;
						-- Increament_read_pointer
						IF s_tmp_results_read_pointer >= G_MAX_WEIGHT_HEIGHT - 1 THEN
							s_tmp_results_read_pointer <= (OTHERS => '0');
						ELSE
							s_tmp_results_read_pointer <= s_tmp_results_read_pointer + 1;
						END IF;
					END IF;
				END IF;
			END IF;
		END IF;

	END PROCESS CONTROL_PROC;

	-- This process only stores the result, when the iteration has concluded
	-- It is necessary so that we can read the old result in order to use it as an input in the next iteration
	RESULT_REG_PROC : PROCESS (s_tmp_complete) IS
	BEGIN

		IF rising_edge(s_tmp_complete) THEN

			FOR i IN s_tmp_results'RANGE LOOP

				s_tmp_results(i) <= s_results((i + 1) * C_RESULT_BIT_WIDTH - 1 DOWNTO i * C_RESULT_BIT_WIDTH);

			END LOOP;

		END IF;

	END PROCESS RESULT_REG_PROC;

	-- This process does the current indexing and c_iteration_amount many static shifts of the output
	-- and also pipelines these through

	INPUT_PIPELINE_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN

				FOR i IN s_shifted_input'RANGE LOOP

					s_shifted_input(i) <= (OTHERS => '0');

				END LOOP;

				s_sliced_input     <= (OTHERS => '0');
				s_shifted_input_en <= '0';
			ELSE
				-- Slice input
				s_sliced_input <= s_tmp_results(to_integer(s_tmp_results_read_pointer));
				-- And then shift them
				FOR i IN s_shifted_input'RANGE LOOP

					-- Calculate all static shifts because they cost next to nothing
					s_shifted_input(i) <= std_logic_vector(shift_right(signed(s_sliced_input),
	                                                   to_integer(unsigned(C_SCALE_VALUES(i)))));

				END LOOP;

				-- only set it to '1' if this is not a rst and not a comlete cycle
				-- If you just set it to '1' this will break the dense layer
				s_sliced_input_en  <= not s_iteration_reset AND not s_tmp_complete;
				s_shifted_input_en <= s_sliced_input_en;
			END IF;
		END IF;

	END PROCESS INPUT_PIPELINE_PROC;

	DENSE_LAYER_INST : ENTITY work.dense_layer
		GENERIC MAP (
			G_BIT_WIDTH          => G_BIT_WIDTH,
			G_OUT_BIT_WIDTH      => C_RESULT_BIT_WIDTH,
			G_MAX_WEIGHT_WIDTH   => G_MAX_WEIGHT_WIDTH,
			G_MAX_WEIGHT_HEIGHT  => G_MAX_WEIGHT_HEIGHT,
			G_WEIGHT_WIDTH_0     => G_WEIGHT_WIDTH_0,
			G_WEIGHT_WIDTH_1     => G_WEIGHT_WIDTH_1,
			G_WEIGHT_WIDTH_2     => G_WEIGHT_WIDTH_2,
			G_WEIGHT_PATH_PREFIX => G_WEIGHT_PATH_PREFIX
		)
		PORT MAP (
			clk                    => clk,
			rst                    => s_iteration_reset,
			i_en                   => s_en,
			i_actual_weight_height => s_actual_weight_height,
			i_actual_weight_width  => s_actual_weight_width,
			i_vector               => s_input,
			i_base_addr            => s_base_addr,
			o_results              => s_results,
			o_comp_complete        => s_tmp_complete
		);

	-- This process shifts and clips the first G_WEIGHT_HEIGHT_2 values
	-- so that it can be passed to the output port.
	-- It also pipelines the output so decrease critical path
	OUTPUT_PIPELINE_PROC : PROCESS (clk) IS
	BEGIN

		IF rising_edge(clk) THEN
			IF rst = '1' THEN

				FOR i IN s_shifted_solutions'RANGE LOOP

					s_shifted_solutions(i) <= (OTHERS => '0');
					s_clipped_solutions(i) <= (OTHERS => '0');

				END LOOP;

				s_shifted_en <= '0';
				s_clipped_en <= '0';
			ELSE

				FOR i IN s_shifted_solutions'RANGE LOOP

					-- Shift the first G_WEIGHT_HEIGHT_2 values with the last scale value
					s_shifted_solutions(i) <= std_logic_vector(shift_right(signed(s_tmp_results(i)),
	                                                       to_integer(unsigned(C_SCALE_VALUES(C_SCALE_VALUES'HIGH)))));
					-- And then clip them accordingly for use in the argmax unit

					IF signed(s_shifted_solutions(i)) > 2 ** (G_BIT_WIDTH - 1) - 1 THEN
						s_clipped_solutions(i) <= std_logic_vector(to_signed(2 ** (G_BIT_WIDTH - 1) - 1, G_BIT_WIDTH));
					ELSIF signed(s_shifted_solutions(i)) < - 2 ** (G_BIT_WIDTH - 1) THEN
						s_clipped_solutions(i) <= std_logic_vector(to_signed(- 2 ** (G_BIT_WIDTH - 1), G_BIT_WIDTH));
					ELSE
						s_clipped_solutions(i) <= s_shifted_solutions(i)(G_BIT_WIDTH - 1 DOWNTO 0);
					END IF;

				END LOOP;

				s_shifted_en <= s_comp_complete;
				s_clipped_en <= s_shifted_en;
			END IF;
		END IF;

	END PROCESS OUTPUT_PIPELINE_PROC;

	-- Set output for the results
	o_comp_complete <= s_clipped_en;

	RESULT_GEN : FOR i IN 0 TO G_WEIGHT_HEIGHT_2 - 1 GENERATE
		o_results((i + 1) * G_BIT_WIDTH - 1 downto i * G_BIT_WIDTH) <= s_clipped_solutions(i);
	END GENERATE RESULT_GEN;

END ARCHITECTURE rtl;
